/**
 * Filter media by category
 */
export function getMediaByCategory(category: MediaAsset['category']): MediaAsset[] {
  return PHUMULANI_MEDIA_INVENTORY.filter(
    (item) => item.category === category && item.publicationStatus === 'published'
  );
}

/**
 * Get media item by ID
 */
export function getMediaById(id: string): MediaAsset | undefined {
  return PHUMULANI_MEDIA_INVENTORY.find((item) => item.id === id);
}

/**
 * Get all published media items
 */
export function getPublishedMedia(): MediaAsset[] {
  return PHUMULANI_MEDIA_INVENTORY.filter((item) => item.publicationStatus === 'published');
}

/**
 * Get media items pending safeguarding review
 */
export function getSafeguardingQueueMedia(): MediaAsset[] {
  return PHUMULANI_MEDIA_INVENTORY.filter(
    (item) => item.safeguardingReviewStatus !== 'cleared_for_public_web' || item.publicationStatus !== 'published'
  );
}
